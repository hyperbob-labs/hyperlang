  def __check_otp_release__ do
    if supported_otp_release?() do
      :ok
    else
      {:error, {:otp_release_mismatch, @otp_release, runtime_otp_release()}}
    end
  end

  def otp_release, do: @otp_release

  def runtime_otp_release do
    case :erlang.system_info(:otp_release) do
      release when is_list(release) -> List.to_string(release)
      release -> to_string(release)
    end
  end

  def supported_otp_release?, do: runtime_otp_release() == @otp_release

  def ensure_supported_otp! do
    if supported_otp_release?() do
      :ok
    else
      raise RuntimeError,
            "Hyperlang stdlib allowlist was generated for OTP #{@otp_release}, " <>
              "but the runtime is OTP #{runtime_otp_release()}; regenerate the frozen allowlist before enabling direct stdlib passthrough"
    end
  end

  def direct_allow, do: @direct_allow
  def modules, do: Map.keys(@direct_allow)

  def allowed?(module, function, arity) do
    arity in (get_in(@direct_allow, [to_string(module), to_string(function)]) || [])
  end
